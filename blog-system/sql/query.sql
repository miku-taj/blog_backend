
-- Create users table
CREATE TABLE users (
    user_id SERIAL PRIMARY KEY,
    username VARCHAR(55) UNIQUE,
    password VARCHAR(255),
    created_at DATE DEFAULT now(),
    updated_at DATE
);

-- Create profiles table
CREATE TABLE profiles (
    profile_id SERIAL PRIMARY KEY,
    user_id INT,
        CONSTRAINT FK_profiles_users_id FOREIGN KEY (user_id) REFERENCES users(user_id),
    date_of_birth DATE,
    location VARCHAR(255),
    about TEXT,
    email VARCHAR(50)
);

-- Create posts table
CREATE TABLE posts (
    post_id SERIAL PRIMARY KEY,
    author_id INT,
    CONSTRAINT FK_posts_users_id FOREIGN KEY (author_id) REFERENCES users(user_id),
    title VARCHAR(255),
    contents TEXT,
    likes_number INT DEFAULT 0,
    created_at DATE DEFAULT now(),
    updated_at DATE,
    is_draft BOOLEAN
);

-- Create post likes table
CREATE TABLE post_likes (
    user_id INT,
    CONSTRAINT FK_likes_users_id FOREIGN KEY (user_id) REFERENCES users(user_id),
    post_id INT,
    CONSTRAINT FK_like_post_id FOREIGN KEY (post_id) REFERENCES posts(post_id),
    PRIMARY KEY (user_id, post_id)
);

-- Create comments table
CREATE TABLE comments (
    comment_id SERIAL PRIMARY KEY,
    user_id INT NOT NULL,
    CONSTRAINT FK_comments_users_id FOREIGN KEY (user_id) REFERENCES users(user_id),
    post_id INT NOT NULL ,
    CONSTRAINT FK_comments_posts_id FOREIGN KEY (post_id) REFERENCES posts(post_id),
    content VARCHAR(8000),
    likes_number INT DEFAULT 0,
    parent_id INT DEFAULT null,
    CONSTRAINT FK_comment_parent_id FOREIGN KEY (parent_id) REFERENCES comments(comment_id),
    created_at DATE DEFAULT now(),
    updated_at DATE DEFAULT null
);

-- Create likes table
CREATE TABLE comment_likes (
                            user_id INT,
                            CONSTRAINT FK_likes_users_id FOREIGN KEY (user_id) REFERENCES users(user_id),
                            comment_id INT,
                            CONSTRAINT FK_like_post_id FOREIGN KEY (comment_id) REFERENCES comments(comment_id),
                            PRIMARY KEY (user_id, comment_id)
);

-- Create subscription table
CREATE TABLE subscriptions (
    user_id INT,
    CONSTRAINT FK_subscription_users_id FOREIGN KEY (user_id) REFERENCES users (user_id),
    author_id INT,
    CONSTRAINT FK_subscription_author_id FOREIGN KEY (author_id) REFERENCES users (user_id),
    PRIMARY KEY (author_id, user_id)
);



